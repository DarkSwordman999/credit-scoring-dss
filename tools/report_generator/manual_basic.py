def _pct(x):
    return f"{x * 100:g} %".replace(".", ",")


def scorecard_rows():
    rows = []
    for key, (label, bins) in logic.SCORECARD.items():
        rows.append(("group", label))
        for lo, hi, pts, text in bins:
            rows.append([text, f"{pts:g}"])
    return rows


def conditions_rows():
    out = []
    prev = 0
    for cls, upper in logic.CLASSES:
        pd = f"от {_pct(prev)} до {_pct(upper)}" if upper <= 1 else f"{_pct(prev)} и выше"
        cond = logic.CONDITIONS[cls]
        if cond:
            out.append([cls, pd, "одобрить", f"{cond[0]:g}".replace(".", ","), f"+{cond[1]:g}".replace(".", ","),
                        _pct(cond[2])])
        else:
            out.append([cls, pd, "отказать", "—", "—", "—"])
        prev = upper
    return out


